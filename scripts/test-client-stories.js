const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const fs = require('node:fs');
const { render } = require('./client-stories-page');
const stories = require('./client-stories.json');
const esc = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
const ctx = { esc, absolute: route => `https://wearjanem.com/${route.replace(/^\//, '')}`, metadata: () => '', sharedHeader: () => '', sharedFooter: () => '' };
const page = { title: 'Client stories', description: 'Delivered pieces', image: stories[0].image };
// Exercise growth without publishing invented customer stories.
const entries = [stories[0], { ...stories[0], id: 'test-second-story', title: 'Test second story', image: 'assets/test-second.jpg', video: undefined }];
const dom = new JSDOM(render(page, ctx, entries));
const doc = dom.window.document;
assert.equal(doc.querySelectorAll('article.story-entry').length, 2);
assert.equal(doc.querySelectorAll('img').length, 2, 'Each card appears once');
assert.equal(doc.querySelectorAll('video').length, 1, 'Video is optional');
const ids = [...doc.querySelectorAll('[id]')].map(el => el.id);
assert.equal(ids.length, new Set(ids).size, 'Stories have distinct anchors');
assert.ok([...doc.querySelectorAll('details')].every(el => !el.open), 'Details start collapsed');
assert.equal(doc.querySelector('video').getAttribute('preload'), 'none');
assert.ok(doc.querySelector('[data-analytics-location="client_story_test-second-story"]').href.includes('Test%20second%20story'));
assert.throws(() => render(page, ctx, [stories[0], stories[0]]), /unique/);
const live = new JSDOM(fs.readFileSync('JaneM_Website/client-stories/index.html', 'utf8'), { runScripts: 'outside-only' });
assert.equal(live.window.document.querySelector('.story-entry h2').textContent, '’Manala’s red occasion dress');
assert.equal(live.window.document.querySelectorAll('.story-entry__body > p:not(.eyebrow)').length, 2, 'The dress story is visible');
let pauses = 0;
live.window.document.querySelector('video').pause = () => pauses++;
live.window.eval(fs.readFileSync('JaneM_Website/client-stories.js', 'utf8'));
live.window.document.querySelector('details').dispatchEvent(new live.window.Event('toggle'));
assert.equal(pauses, 1, 'Closing the reveal stops hidden playback');
console.log('Client story checks passed: multiple entries, no repeated cards, optional video, unique anchors and paused hidden media.');
